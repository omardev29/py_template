@pytest.mark.parametrize("name", NAMES)
def test_every_task_runs_the_launcher_as_a_process(name: str) -> None:
    cfg = make(name)
    tasks = task_list(cfg)
    labels = [t["label"] for t in tasks]
    assert len(labels) == len(set(labels)), labels
    for t in tasks:
        args = t["args"][1:]
        assert t["type"] == "process"
        assert t["command"] == "/bin/sh" and t["args"][0] == f"{WS}/deploy"
        assert t["windows"] == {"command": WS + "\\deploy.cmd", "args": args}
        assert args[0] in COMMANDS or args[0] in cfg.tasks, args
        assert t["options"]["cwd"] == WS
        assert t["detail"].startswith(f"./deploy {' '.join(args)}  |  "), t["detail"]
        assert len(t["detail"].split("  |  ", 1)[1]) > 5
        assert t["icon"]["id"]
        assert isinstance(t["problemMatcher"], list)
        assert "isBackground" not in t
        has_ruff = "ruff" in owners(t)
        assert (t["options"].get("env") == {"RUFF_OUTPUT_FORMAT": "concise"}) == has_ruff, t["label"]
    for kind in ("test", "build"):
        defaults = [t["label"] for t in tasks if isinstance(t.get("group"), dict) and t["group"]["kind"] == kind]
        assert defaults == [f"deploy: {kind}"]


@pytest.mark.parametrize("name", NAMES)
def test_buttons_map_to_tasks_in_order(name: str) -> None:
    cfg = make(name)
    tasks = task_list(cfg)
    wanted = list(dict.fromkeys(" ".join(b.split()) for b in cfg.vscode.buttons))
    shown = [t for t in tasks if "statusbar" in t["options"]]
    assert len(shown) == len(wanted)
    # actboy168.tasks creates the buttons in file order: the button tasks lead, in [vscode] order
    assert tasks[: len(shown)] == shown
    for button, t in zip(wanted, shown, strict=True):
        args = " ".join(t["args"][1:])
        assert button in (args, t["label"].removeprefix("deploy: ")), (button, t["label"])
        bar = t["options"]["statusbar"]
        assert bar["hide"] is False
        assert "$(" not in bar["label"]  # the extension prefixes the task's icon itself
        assert bar["label"].lower() == t["label"].removeprefix("deploy: ").lower()


