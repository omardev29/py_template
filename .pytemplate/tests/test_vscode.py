def _classify(lines: list[str]) -> dict[str, list[str]]:
    matchers = matchers_by_kind()
    out: dict[str, list[str]] = {}
    for line in lines:
        matched = [k for k, m in matchers.items() if re.search(m["pattern"]["regexp"], line)]
        assert len(matched) <= 1, (line, matched)
        if matched:
            out.setdefault(matched[0], []).append(line)
    return out


