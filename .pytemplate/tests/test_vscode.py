def all_matchers() -> list[dict[str, Any]]:
    seen: dict[str, dict[str, Any]] = {}
    for name in NAMES:
        for t in task_list(make(name)):
            for m in t["problemMatcher"]:
                seen[json.dumps(m, sort_keys=True)] = m
    return list(seen.values())


# Python-only regexp syntax that JavaScript (VS Code) rejects or reads differently
JS_UNSAFE = re.compile(r"\(\?P|\(\?<[^=!]|\(\?[aiLmsux]|\(\?#|\(\?>|\\[AZz]|[*+?}][+]")


def test_matcher_regexps_are_portable() -> None:
    matchers = all_matchers()
    assert {m["owner"] for m in matchers} == {f"pytemplate-{k}" for k in ("ruff", "mypy", "rules", "pyright", "mypyc", "pytest")}
    for m in matchers:
        pattern = m["pattern"]
        regex = re.compile(pattern["regexp"])
        assert not JS_UNSAFE.search(pattern["regexp"]), pattern["regexp"]
        assert pattern["regexp"].startswith("^") and pattern["regexp"].endswith("$")
        groups = [v for k, v in pattern.items() if k != "regexp"]
        assert max(groups) <= regex.groups and len(set(groups)) == len(groups)
        assert m["fileLocation"][0] in ("relative", "autoDetect")
        assert m.get("severity", "error") in ("error", "warning", "info")


def matchers_by_kind() -> dict[str, dict[str, Any]]:
    """Every matcher, from a config that has all of them (package myapp, mypy errors blocking)."""
    cfg = make("basedpyright")
    out: dict[str, dict[str, Any]] = {}
    for m in vscode.problem_matchers(cfg, {"ruff", "mypy", "rules", "pyright", "mypyc", "pytest"}, ["mypyc"]):
        kind = m["owner"].removeprefix("pytemplate-")
        out[kind + ("-note" if m.get("severity") == "info" else "")] = m
    return out


