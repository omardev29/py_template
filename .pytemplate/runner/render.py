"""Generation of the configuration files from pytemplate.toml + .pytemplate/templates.

Generated files (committed; NOT edited by hand):
  .python-version, .mypy.ini, .ruff.toml, pyrightconfig.json, .github/workflows/ci.yml,
  plus each editor's files (editors/vscode.py: .vscode/*.json; editors/nvim.py: .lazy.lua
  and .pytemplate/editor.json)

.pytemplate/state.json stores the hash (normalized to LF) of what we last wrote:
if a generated file differs from that hash, someone edited it by hand and it is not
overwritten without --force. In addition, pyproject.toml has two managed parts
(requires-python and a [tool.uv] block between markers) that are only rewritten by
`mode`/`lock`, because changing them requires re-locking uv.lock. They are compared by
meaning (parsed TOML), so a TOML formatter may lay them out as it likes.
"""

from __future__ import annotations

import copy
import difflib
import hashlib
import json
import re
import tomllib
from pathlib import Path
from typing import Any

from . import presets, proc, ui
from .config import Config, compiled_paths
from .envs import MIN_UV
from .project import PYPROJECT, ROOT, STATE_FILE, TEMPLATES, rel
from .ui import DeployError

HEADER = "GENERATED by ./deploy from pytemplate.toml and .pytemplate/templates: do not edit by hand"
MARK_BEGIN = "# >>> pytemplate"
MARK_END = "# <<< pytemplate"
STATE_COMMENT = "Hashes of the files generated by ./deploy (detects hand edits)"


# --- profiles ----------------------------------------------------------------------------------

# The profile keys the runner reads, with their type: a wrong one would crash deep inside a
# generator instead of naming the file.
_PROFILE_TABLES = ("mypy", "mypy_compiled", "pyright", "pyright_compiled", "basedpyright_compiled", "ruff", "vscode")
_PROFILE_FLAGS = ("blocking", "skip_mypy")


def load_profile(name: str) -> dict[str, Any]:
    """Return the typing profile `templates/typing/<name>.toml` (a BOM is fine: PS 5.1 and some
    Windows editors add one). Invalid TOML or a known key of the wrong type is a DeployError."""
    path = TEMPLATES / "typing" / f"{name}.toml"
    if not path.is_file():
        raise DeployError(f"typing profile not found: {rel(path)}")
    try:
        data = tomllib.loads(path.read_text(encoding="utf-8-sig"))
    except UnicodeDecodeError:
        raise DeployError(f"{rel(path)} is not UTF-8 text: save it as UTF-8") from None
    except tomllib.TOMLDecodeError as e:
        raise DeployError(f"{rel(path)} is not valid TOML: {e}") from None
    _check_profile(path, data)
    return data


def _check_profile(path: Path, data: dict[str, Any]) -> None:
    def wrong(key: str, wanted: str) -> DeployError:
        return DeployError(f"{rel(path)}: '{key}' must be {wanted}")

    for key in _PROFILE_TABLES:
        if key in data and not isinstance(data[key], dict):
            raise wrong(key, "a table")
    for key in _PROFILE_FLAGS:
        if key in data and not isinstance(data[key], bool):
            raise wrong(key, "true or false")
    if not isinstance(data.get("description", ""), str):
        raise wrong("description", "a string")
    ruff = data.get("ruff", {})
    for key in ("select", "ignore"):
        value = ruff.get(key, [])
        if not isinstance(value, list) or not all(isinstance(v, str) for v in value):
            raise wrong(f"ruff.{key}", "a list of strings")
    if not isinstance(ruff.get("exit_zero", False), bool):
        raise wrong("ruff.exit_zero", "true or false")


def typings_dir() -> Path | None:
    """Return the project's own stubs (e.g. the raylib ones fixed by the preset), if any."""
    path = ROOT / "typings"
    return path if path.is_dir() else None


def compiled_patterns(cfg: Config) -> list[str]:
    return [f"{m}.*" for m in cfg.compile.modules]


# --- mypy ----------------------------------------------------------------------------------------


def _ini_value(value: Any) -> str:
    if isinstance(value, bool):
        return "True" if value else "False"
    if isinstance(value, list):
        return ", ".join(str(v) for v in value)
    return str(value)


def _ini_section(name: str, options: dict[str, Any]) -> list[str]:
    lines = [f"[{name}]"]
    lines += [f"{k} = {_ini_value(v)}" for k, v in options.items()]
    return [*lines, ""]


def mypy_ini(cfg: Config, profile: str, *, for_compile: bool = False) -> str:
    """Return the mypy config. `for_compile`: the one mypyc uses from the stage (absolute paths)."""
    data = load_profile(profile)
    head: dict[str, Any] = {}
    typings = typings_dir()
    if for_compile:
        if typings:
            head["mypy_path"] = typings.as_posix()
    else:
        head["mypy_path"] = ["src", "typings"] if typings else "src"
        head["files"] = ["src", "tests"] if (ROOT / "tests").is_dir() else "src"
    lines = [f"# {HEADER}", f"# Typing profile: {profile} ({data.get('description', '')})", ""]
    lines += _ini_section("mypy", {**head, **data.get("mypy", {})})
    # One section per module pattern, later options winning: mypy refuses a repeated section
    # name, and a pattern repeated in another section REPLACES the earlier options (an override
    # of "{pkg}.core.*" would have dropped the compiled rules).
    sections: dict[str, dict[str, Any]] = {}
    compiled = data.get("mypy_compiled")
    if compiled:
        for pattern in compiled_patterns(cfg):
            sections.setdefault(pattern, {}).update(compiled)
        # compile.exclude stays interpreted: back to the global value (a module or a whole
        # subpackage: `x.*` covers x itself, and mypy prefers the longer pattern)
        relaxed = {key: data.get("mypy", {}).get(key, False) for key in compiled}
        for module in cfg.compile.exclude:
            sections.setdefault(f"{module}.*", {}).update(relaxed)
    for override in cfg.typing.mypy_overrides:
        modules = override["module"]
        names = modules if isinstance(modules, list) else [modules]
        opts = {k: v for k, v in override.items() if k != "module"}
        for name in names:
            sections.setdefault(name.replace("{pkg}", cfg.pkg), {}).update(opts)
    for name, opts in sections.items():
        lines += _ini_section(f"mypy-{name}", opts)
    return "\n".join(lines).rstrip("\n") + "\n"


def mypy_cli_args(cfg: Config, python: Path) -> list[str]:
    """With PyPy supported, the code must be valid on 3.11: these args make mypy check that."""
    if not cfg.pypy_enabled:
        return []
    return ["--python-version", cfg.min_python, "--python-executable", str(python)]


# --- pyright / basedpyright ----------------------------------------------------------------------


def pyright_config(cfg: Config, profile: str, *, absolute: bool = False) -> dict[str, Any]:
    """`absolute`: for a copy outside the root (pyright resolves paths relative to the file)."""
    data = load_profile(profile)

    def path(p: str) -> str:
        return (ROOT / p).as_posix() if absolute else p

    include = [path("src"), path("tests")] if (ROOT / "tests").is_dir() else [path("src")]
    conf: dict[str, Any] = {
        "include": include,
        "exclude": ["**/node_modules", "**/__pycache__", "**/.*", path("dist"), path("build")],
        "extraPaths": [path("src")],
        "pythonVersion": cfg.min_python,
        "venvPath": path("."),
        "venv": ".venv",
    }
    if typings_dir():
        conf["stubPath"] = path("typings")
    conf.update(data.get("pyright", {}))
    # compile.exclude (modules and subpackages that stay interpreted) is left out of the rules
    # for compiled code: pyright has no exclusion inside `strict`, so a compiled package that
    # holds an excluded module is listed by its other files and folders
    excluded = {rel for m in cfg.compile.exclude for rel in _module_paths(m)}
    compiled = [p for top in compiled_paths(cfg) for p in _paths_without(f"src/{top}", excluded)]
    if data.get("pyright_compiled", {}).get("strict"):
        conf["strict"] = [path(p) for p in compiled]
    based = data.get("basedpyright_compiled")
    if cfg.typing.editor == "basedpyright" and based:
        # The first environment that matches a file wins: the excluded ones come first, without the Any rules
        conf["executionEnvironments"] = [
            {"root": path(p), "extraPaths": [path("src")]} for p in sorted(excluded) if (ROOT / p).exists()
        ] + [{"root": path(p), "extraPaths": [path("src")], **based} for p in compiled if (ROOT / p).exists()]
    return conf


def _module_paths(module: str) -> tuple[str, str]:
    """The two paths (relative to ROOT) a dotted module can have: a .py file or a package folder."""
    base = "src/" + module.replace(".", "/")
    return f"{base}.py", base


def _paths_without(top: str, excluded: set[str]) -> list[str]:
    """`top` (a path relative to ROOT) as the fewest files and folders that leave `excluded` out."""
    if top in excluded:
        return []
    if not any(e.startswith(top + "/") for e in excluded) or not (ROOT / top).is_dir():
        return [top]
    out: list[str] = []
    for child in sorted((ROOT / top).iterdir(), key=lambda p: p.name):
        if child.name.startswith((".", "__pycache__")) or not (child.is_dir() or child.suffix in (".py", ".pyi")):
            continue
        out += _paths_without(f"{top}/{child.name}", excluded)
    return out


# --- ruff ----------------------------------------------------------------------------------------


def _toml_scalar(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, list):
        return "[" + ", ".join(_toml_scalar(v) for v in value) + "]"
    if isinstance(value, dict):
        return "{ " + ", ".join(f"{_toml_key(k)} = {_toml_scalar(v)}" for k, v in value.items()) + " }"
    raise TypeError(value)


def _toml_key(key: str) -> str:
    return key if re.fullmatch(r"[A-Za-z0-9_-]+", key) else json.dumps(key)


def to_toml(data: dict[str, Any], prefix: str = "") -> str:
    """Serialize to minimal TOML (nested tables, lists and simple values)."""
    scalars = {k: v for k, v in data.items() if not isinstance(v, dict) or not v}
    tables = {k: v for k, v in data.items() if k not in scalars}
    out: list[str] = []
    for k, v in scalars.items():
        out.append(f"{_toml_key(k)} = {_toml_scalar(v)}")
    for k, v in tables.items():
        name = f"{prefix}.{_toml_key(k)}" if prefix else _toml_key(k)
        out.append("")
        out.append(f"[{name}]")
        body = to_toml(v, name)
        if body:
            out.append(body)
    return "\n".join(out).strip("\n")


def ruff_config(cfg: Config, profile: str, *, absolute: bool = False) -> dict[str, Any]:
    """`absolute`: for copies outside the root (ruff resolves paths relative to the file itself)."""
    data = load_profile(profile).get("ruff", {})

    def path(p: str) -> str:
        return (ROOT / p).as_posix() if absolute else p

    select = list(data.get("select", []))
    lint: dict[str, Any] = {"select": select, "ignore": list(data.get("ignore", []))}
    if "ANN" in select:
        lint["per-file-ignores"] = {"tests/**" : ["ANN"]}
        lint["flake8-annotations"] = {"mypy-init-return": True}
    return {
        "target-version": "py" + cfg.min_python.replace(".", ""),
        "line-length": 100,
        "src": [path("src"), path("tests")],
        "extend-exclude": [path(p) for p in (".build", "dist", ".pytemplate", "typings")],
        "lint": lint,
        "format": {"docstring-code-format": True},
    }


# --- JSONC ---------------------------------------------------------------------------------------


def jsonc(data: Any) -> str:
    """Serialize a generated JSON file with the HEADER comment (VS Code and pyright read JSONC)."""
    try:
        body = json.dumps(data, indent=4, ensure_ascii=False, allow_nan=False)
    except (TypeError, ValueError) as e:  # a TOML date/time, or nan/inf (invalid JSON)
        raise DeployError(f"a generated JSON file would hold a value JSON cannot represent: {e}") from None
    return f"// {HEADER}\n" + body + "\n"


# --- CI ------------------------------------------------------------------------------------------

CI_PLACEHOLDERS = ("__HEADER__", "__MATRIX__", "__LINUX_DEPS__", "__NAME__", "__BUILD_BACKEND__")


def ci_workflow(cfg: Config) -> str:
    path = TEMPLATES / "ci.yml"
    try:
        text = _norm(path.read_text(encoding="utf-8"))
    except UnicodeDecodeError:
        raise DeployError(f"{rel(path)} is not UTF-8 text: save it as UTF-8") from None
    builds = [b for b in ("mypyc", "cpython") if cfg.supports(b)]
    matrix: list[str] = []
    for os_name in ("ubuntu-latest", "windows-latest", "macos-latest"):
        backends = list(cfg.backend.supported)
        if os_name.startswith("macos") and cfg.app.preset == "raylib" and "pypy" in backends:
            backends.remove("pypy")  # raylib publishes no PyPy wheels for macOS arm64
        if not backends:
            continue  # nothing this OS can sync, test or build (raylib with PyPy only, on macOS)
        matrix += [f"          - os: {os_name}", f'            backends: "{" ".join(backends)}"']
    linux = ""
    if cfg.app.preset == "raylib":
        linux = (
            "      - name: System libraries for raylib (Linux)\n"
            "        if: runner.os == 'Linux'\n"
            "        run: sudo apt-get update && sudo apt-get install -y libgl1 libx11-6 libxrandr2 libxinerama1 libxcursor1 libxi6"
        )
    # __LINUX_DEPS__ stands alone on its line: the whole line goes when there is nothing to install
    text = re.sub(r"(?m)^[ \t]*__LINUX_DEPS__[ \t]*\n", lambda m: linux + "\n" if linux else "", text)
    out = (
        text.replace("__HEADER__", HEADER)
        .replace("__MATRIX__", "\n".join(matrix))
        .replace("__NAME__", cfg.app.name)
        .replace("__BUILD_BACKEND__", builds[0] if builds else cfg.backend.active)
    )
    left = [p for p in CI_PLACEHOLDERS if p in out]
    if left:
        raise DeployError(f"{rel(path)}: {', '.join(left)} not replaced (__LINUX_DEPS__ must be alone on its line)")
    return out


# --- output set ---------------------------------------------------------------------------------


def outputs(cfg: Config) -> dict[str, str]:
    """Return every generated file: {path relative to the root: content}."""
    from .editors import nvim, vscode

    profile = cfg.profile_for()
    files = {
        ".python-version": cfg.python.cpython + "\n",
        ".mypy.ini": mypy_ini(cfg, profile),
        ".ruff.toml": f"# {HEADER}\n# Typing profile: {profile}\n\n" + to_toml(ruff_config(cfg, profile)) + "\n",
        "pyrightconfig.json": jsonc(pyright_config(cfg, profile)),
    }
    files.update(vscode.outputs(cfg, profile))
    files.update(nvim.outputs(cfg, profile))
    if (TEMPLATES / "ci.yml").is_file():
        files[".github/workflows/ci.yml"] = ci_workflow(cfg)
    return files


def _norm(text: str) -> str:
    return text.lstrip("\ufeff").replace("\r\n", "\n")


def _digest(text: str) -> str:
    return hashlib.sha256(_norm(text).encode("utf-8")).hexdigest()


def _read_state() -> dict[str, Any]:
    """state.json as an object: {} when it is missing, unreadable (not UTF-8: PS 5.1 `>` writes
    UTF-16), not JSON or not an object. A BOM (an editor, PS 5.1 Set-Content) is fine."""
    try:
        data = json.loads(STATE_FILE.read_text(encoding="utf-8-sig"))
    except (OSError, ValueError):  # ValueError: UnicodeDecodeError and JSONDecodeError
        return {}
    return data if isinstance(data, dict) else {}


def _load_state() -> dict[str, str]:
    """The recorded hashes {path: sha256}. Anything malformed counts as not recorded."""
    files = _read_state().get("files")
    if not isinstance(files, dict):
        return {}
    return {k: v for k, v in files.items() if isinstance(k, str) and isinstance(v, str) and re.fullmatch(r"[0-9a-f]{64}", v)}


def _save_state(files: dict[str, str]) -> None:
    """Write the hashes, keeping every other top-level key (`./deploy apply` records its own) and,
    when the file has both of ours, the key order (no churn in git)."""
    old = _read_state()
    body: dict[str, Any] = {} if {"comment", "files"} <= old.keys() else {"comment": None, "files": None}
    body.update(old)
    body["comment"] = STATE_COMMENT
    body["files"] = dict(sorted(files.items()))
    try:
        STATE_FILE.parent.mkdir(parents=True, exist_ok=True)
        STATE_FILE.write_text(json.dumps(body, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    except OSError as e:
        raise DeployError(f"cannot write {rel(STATE_FILE)}: {e.strerror or e}") from None


def _write(path: str, target: Path, content: str) -> None:
    try:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8", newline="\n")
    except OSError as e:
        raise DeployError(f"cannot write the generated file {path}: {e.strerror or e}") from None


def apply(cfg: Config, *, force: bool = False, check: bool = False, show_diff: bool = False) -> tuple[list[str], list[str]]:
    """Write the outdated files. Return (changed, hand_edited). --dry-run behaves like `check`."""
    check = check or proc.DRY_RUN
    state = _load_state()
    changed: list[str] = []
    edited: list[str] = []
    new_state = dict(state)
    for path, content in outputs(cfg).items():
        target = ROOT / path
        new_hash = _digest(content)
        if target.exists() and not target.is_file():
            raise DeployError(f"{path} is generated, but a folder of that name is in the way: remove it")
        if target.is_file():
            try:
                current = target.read_text(encoding="utf-8", errors="replace")
            except OSError as e:
                raise DeployError(f"cannot read the generated file {path}: {e.strerror or e}") from None
            current_hash = _digest(current)
            if current_hash == new_hash:
                new_state[path] = new_hash
                continue
            recorded = state.get(path)
            if recorded is not None and recorded != current_hash and not force:
                edited.append(path)
                if show_diff:
                    diff = difflib.unified_diff(
                        content.splitlines(), _norm(current).splitlines(), f"{path} (generated)", f"{path} (current)", lineterm=""
                    )
                    ui.report("\n".join(diff))  # --diff: shown even with -q
                continue
        changed.append(path)
        if not check:
            _write(path, target, content)
            new_state[path] = new_hash
    if not check and new_state != state:
        _save_state(new_state)
    return changed, edited


def auto(cfg: Config, *, force: bool = False) -> None:
    """Silently render before every command: print one line if something changed."""
    changed, edited = apply(cfg, force=force)
    if changed:
        ui.info(f"render: {'would update' if proc.DRY_RUN else 'updated'} {', '.join(changed)}")
    if edited:
        ui.warn(
            f"not overwriting hand-edited generated files: {', '.join(edited)}\n"
            "  Change pytemplate.toml or .pytemplate/templates instead, or use ./deploy render --force"
        )
    if pyproject_outdated(cfg):
        ui.warn(
            "pyproject.toml does not match pytemplate.toml (backend.supported / python / preset).\n"
            "  Apply it and re-lock with: ./deploy lock"
        )


# --- pyproject.toml (managed parts) ---------------------------------------------------------------


def managed_block(cfg: Config) -> str:
    def minor_range(version: str) -> str:
        major, minor = version.split(".")
        return f"python_full_version >= '{version}' and python_full_version < '{major}.{int(minor) + 1}'"

    lines = [
        f"{MARK_BEGIN}: generated from pytemplate.toml by ./deploy; do not edit up to the closing marker",
        "# uv.lock only resolves for the pinned minor version (e.g. without the 3.15 branch, where",
        "# libraries such as raylib have no wheels yet). To change it: python.cpython + ./deploy lock",
        "environments = [",
        f"    \"implementation_name == 'cpython' and {minor_range(cfg.python.cpython)}\",",
    ]
    if cfg.pypy_enabled:
        lines.append(f"    \"implementation_name == 'pypy' and {minor_range(cfg.pypy_minor)}\",")
    lines.append("]")
    if cfg.pypy_enabled:
        lines += [
            "# PyPy ships cffi built in; uv does not see it and would try to build the one from PyPI",
            "override-dependencies = [\"cffi>=1.15.1; implementation_name == 'cpython'\"]",
        ]
    for key, value in presets.uv_extras(cfg).items():
        lines.append(f"{key} = {_toml_scalar(value)}")
    # The oldest uv that installs the pinned interpreters (envs.MIN_UV): an older uv stops with
    # "Required uv version ... does not match" (uv >= 0.5.14 reads it; doctor also checks)
    lines.append(f'required-version = ">={MIN_UV}"')
    lines.append(f'python-preference = "only-managed"  {MARK_END}')
    return "\n".join(lines)


# The opening marker is a whole line, "# >>> pytemplate" or "# >>> pytemplate: ..."; the closing one
# ends its line (an inline comment on the last key, so uv/toml_edit insertions cannot detach it).
# presets.EXTRA_BEGIN/EXTRA_END ("# >>> pytemplate-preset" / "# <<< pytemplate-preset") share the
# prefix and are never taken for them.
_BEGIN_RE = re.compile(r"[ \t]*" + re.escape(MARK_BEGIN) + r"(?:[ \t]*|:.*)")
_END_RE = re.compile(re.escape(MARK_END) + r"[ \t]*$")
_HEADER_RE = re.compile(r"[ \t]*\[\[?[ \t]*[A-Za-z0-9_.\"' \t-]+\]\]?[ \t]*(?:#.*)?")  # [table] / [[array]]
_UV_HEADER = re.compile(r"[ \t]*\[[ \t]*tool[ \t]*\.[ \t]*uv[ \t]*\][ \t]*(?:#.*)?")
_PROJECT_HEADER = re.compile(r"[ \t]*\[[ \t]*project[ \t]*\][ \t]*(?:#.*)?")
# requires-python in any TOML string form (triple-quoted first, so `""">=3.14"""` is not read as
# the empty string `""`), with a quoted key or not, at any indent
_REQUIRES_PYTHON = re.compile(
    r"""(?m)^([ \t]*(?:requires-python|"requires-python"|'requires-python')[ \t]*=[ \t]*)"""
    r"""('{3}[\s\S]*?'{3}|"{3}[\s\S]*?"{3}|'[^'\n]*'|"(?:[^"\\\n]|\\.)*")"""
)


def _split(text: str) -> list[str]:
    """The lines of an LF text: only "\\n" breaks a line (str.splitlines would also break inside a
    string at a form feed or U+2028)."""
    lines = text.split("\n")
    if lines and not lines[-1]:
        lines.pop()
    return lines


def _managed_bounds(lines: list[str]) -> tuple[int, int] | None:
    """Return the first and last line of the managed block; None when both markers are missing
    (the block is then inserted). A DeployError explains any other state of the markers."""
    begins = [i for i, ln in enumerate(lines) if _BEGIN_RE.fullmatch(ln)]
    ends = [i for i, ln in enumerate(lines) if _END_RE.search(ln)]
    if not begins and not ends:
        return None
    if len(begins) > 1 or len(ends) > 1:
        problem = "a marker appears more than once"
    elif not begins:
        problem = f"the opening marker line '{MARK_BEGIN}: ...' is missing"
    elif not ends:
        problem = f"the closing marker '{MARK_END}' (a comment at the end of the python-preference line) is missing"
    elif ends[0] < begins[0]:
        problem = "the closing marker comes before the opening one"
    else:
        begin, end = begins[0], ends[0]
        table = next((ln for ln in reversed(lines[:begin]) if _HEADER_RE.fullmatch(ln)), "")
        if not _UV_HEADER.fullmatch(table):
            problem = "the block is not in the [tool.uv] table"
        elif any(_HEADER_RE.fullmatch(ln) for ln in lines[begin : end + 1]):
            problem = "a table header is between the markers"
        else:
            return begin, end
    raise DeployError(
        f"pyproject.toml: the [tool.uv] block managed by pytemplate is broken: {problem}.\n"
        f"  It starts with the line '{MARK_BEGIN}: ...' and ends with the python-preference line, which\n"
        f"  carries '{MARK_END}' as a comment. Restore the markers, or delete the whole block (both\n"
        "  markers and the keys between them) and run ./deploy lock to write it again"
    )


def _set_requires_python(lines: list[str], min_python: str) -> list[str]:
    """Set [project] requires-python (inserted under the header when missing: uv would default to
    the running interpreter's minor)."""
    start = next((i for i, ln in enumerate(lines) if _PROJECT_HEADER.fullmatch(ln)), None)
    if start is None:
        return lines  # no [project] table: _verify says so
    stop = next((i for i in range(start + 1, len(lines)) if _HEADER_RE.fullmatch(lines[i])), len(lines))
    value = f'">={min_python}"'
    section, found = _REQUIRES_PYTHON.subn(lambda m: m.group(1) + value, "\n".join(lines[start + 1 : stop]), count=1)
    body = section.split("\n") if stop > start + 1 else []
    if not found:
        body.insert(0, f"requires-python = {value}")
    return [*lines[: start + 1], *body, *lines[stop:]]


def pyproject_expected(cfg: Config, text: str) -> str:
    """Return `text` (LF) with the managed parts rewritten: [project] requires-python and the marked
    block of [tool.uv] (inserted after the [tool.uv] header, or in a new [tool.uv] table, when both
    markers are missing). Unusable markers are a DeployError."""
    lines = _set_requires_python(_split(text), cfg.min_python)
    block = _split(managed_block(cfg))
    bounds = _managed_bounds(lines)
    if bounds:
        lines[bounds[0] : bounds[1] + 1] = block
    else:
        header = next((i for i, ln in enumerate(lines) if _UV_HEADER.fullmatch(ln)), None)
        if header is None:
            while lines and not lines[-1].strip():
                lines.pop()
            lines += ["", "[tool.uv]", *block]
        else:
            lines[header + 1 : header + 1] = block
    return "\n".join(lines) + "\n"


def _table(data: Any, *keys: str) -> dict[str, Any]:
    for key in keys:
        data = data.get(key) if isinstance(data, dict) else None
    return data if isinstance(data, dict) else {}


def _without_managed(data: dict[str, Any], uv_keys: set[str]) -> dict[str, Any]:
    """`data` without [project] requires-python and the given [tool.uv] keys (empty tables dropped)."""
    out = copy.deepcopy(data)
    _table(out, "project").pop("requires-python", None)
    tool = _table(out, "tool")
    if "uv" in tool and isinstance(tool["uv"], dict):
        for key in uv_keys:
            tool["uv"].pop(key, None)
        if not tool["uv"]:
            del tool["uv"]
        if not tool:
            del out["tool"]
    return out


def _verify(cfg: Config, text: str, new: str) -> None:
    """Refuse (DeployError) a rewrite that gives invalid TOML, misses a managed value or would
    change anything outside the managed parts: nothing is ever lost silently."""
    try:
        old = tomllib.loads(text)
    except tomllib.TOMLDecodeError as e:
        raise DeployError(f"pyproject.toml is not valid TOML ({e}).\n  Fix it, then run ./deploy lock") from None
    managed = tomllib.loads(managed_block(cfg))
    try:
        data = tomllib.loads(new)
    except tomllib.TOMLDecodeError as e:
        raise DeployError(
            f"pyproject.toml: writing the parts managed by pytemplate would give invalid TOML ({e}).\n"
            f"  Does [tool.uv] repeat a managed key ({', '.join(managed)}) outside the markers? Delete it there\n"
            "  (./deploy lock writes the managed block again), or restore the markers"
        ) from None
    lines = _split(text)
    bounds = _managed_bounds(lines)
    old_keys: set[str] = set()
    if bounds:
        try:
            old_keys = set(tomllib.loads("\n".join(lines[bounds[0] : bounds[1] + 1])))
        except tomllib.TOMLDecodeError:
            pass  # the comparison below reports it
    if _without_managed(old, old_keys) != _without_managed(data, set(managed)):
        raise DeployError(
            "pyproject.toml: rewriting the parts managed by pytemplate would also change other settings\n"
            "  (is a key or table of yours between the markers?). Move it out of the managed block,\n"
            "  then run ./deploy lock"
        )
    if _table(data, "project").get("requires-python") != f">={cfg.min_python}":
        raise DeployError("pyproject.toml: requires-python could not be set: is the [project] table missing?")
    uv = _table(data, "tool", "uv")
    if any(uv.get(key) != value for key, value in managed.items()):
        raise DeployError("pyproject.toml: the managed keys did not end up in [tool.uv]: restore the markers")


def _read_pyproject() -> str:
    try:
        return _norm(PYPROJECT.read_text(encoding="utf-8"))
    except FileNotFoundError:
        raise DeployError("pyproject.toml not found") from None
    except UnicodeDecodeError:
        raise DeployError("pyproject.toml is not UTF-8 text: save it as UTF-8") from None
    except OSError as e:
        raise DeployError(f"cannot read pyproject.toml: {e.strerror or e}") from None


def _same_meaning(text: str, new: str) -> bool:
    """Whether `new` says the same as `text` (both valid TOML: _verify ran). A TOML formatter such as
    taplo (Even Better TOML, LazyVim's toml extra) re-indents and re-spaces comments; that is fine."""
    return text == new or tomllib.loads(text) == tomllib.loads(new)


def check_pyproject(cfg: Config) -> None:
    """Raise the DeployError write_pyproject would raise, without writing: a preflight for commands
    that change other files first (mode, rename, the preset step of new)."""
    text = _read_pyproject()
    _verify(cfg, text, pyproject_expected(cfg, text))


def pyproject_outdated(cfg: Config) -> bool:
    """Whether the managed parts of pyproject.toml mean something else than pytemplate.toml says,
    or cannot be applied (write_pyproject then says why). Never raises: render.auto, doctor and
    the pre-commit hook call it."""
    try:
        text = _read_pyproject()
        new = pyproject_expected(cfg, text)
        _verify(cfg, text, new)
    except DeployError:
        return True
    return not _same_meaning(text, new)


def write_pyproject(cfg: Config) -> bool:
    """Rewrite the managed parts of pyproject.toml. Return whether they changed (or, under
    --dry-run, would change: nothing is written then). A file that only differs in layout or
    comments is left as it is; one that cannot be rewritten safely is a DeployError."""
    text = _read_pyproject()
    new = pyproject_expected(cfg, text)
    _verify(cfg, text, new)
    if _same_meaning(text, new):
        return False
    if not proc.DRY_RUN:
        try:
            PYPROJECT.write_text(new, encoding="utf-8", newline="\n")
        except OSError as e:
            raise DeployError(f"cannot write pyproject.toml: {e.strerror or e}") from None
    return True


def pyproject_message() -> str:
    """Return the line printed after write_pyproject returned True."""
    verb = "would update" if proc.DRY_RUN else "updated"
    return f"pyproject.toml: {verb} the parts managed by pytemplate"
