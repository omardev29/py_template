# VS Code runs `RegExp.exec(line)`, which searches anywhere in the line: the tests use re.search.
def fields(m: dict[str, Any], match: re.Match[str]) -> dict[str, str | None]:
    return {key: match.group(index) for key, index in m["pattern"].items() if key != "regexp"}


@pytest.mark.parametrize(("line", "kind", "expected"), SAMPLES, ids=[f"{i}-{s[1]}" for i, s in enumerate(SAMPLES)])
def test_matcher_samples(line: str, kind: str | None, expected: dict[str, str | None]) -> None:
    matchers = matchers_by_kind()
    hits = {k: re.search(m["pattern"]["regexp"], line) for k, m in matchers.items()}
    matched = [k for k, hit in hits.items() if hit]
    assert matched == ([kind] if kind else []), (line, matched)
    if kind:
        hit = hits[kind]
        assert hit is not None
        got = fields(matchers[kind], hit)
        for key, value in expected.items():
            assert got[key] == value, (line, key, got)


