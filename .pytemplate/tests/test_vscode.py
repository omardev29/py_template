def _run(argv: list[str], cwd: Path, **env: str) -> list[str]:
    full = {k: v for k, v in os.environ.items() if k != "RUFF_OUTPUT_FORMAT"}
    full.update({"NO_COLOR": "1", **env})
    r = subprocess.run(argv, cwd=cwd, env=full, capture_output=True, text=True, encoding="utf-8", timeout=300, check=False)
    return (r.stdout + r.stderr).splitlines()


def _needs(module: str) -> None:
    if importlib.util.find_spec(module) is None:
        pytest.skip(f"{module} is not installed in this environment")


@pytest.fixture
def scratch(tmp_path: Path) -> Path:
    (tmp_path / "src").mkdir()
    (tmp_path / "tests").mkdir()
    (tmp_path / "src" / "demo_mod.py").write_text(
        'import os\n\n\ndef f(x: int) -> str:\n    return x + 1\n\n\nreveal_type(f)\nprint(undefined_name)\n', encoding="utf-8"
    )
    (tmp_path / "tests" / "test_demo.py").write_text(
        "def test_one() -> None:\n    assert 1 + 1 == 3\n\n\ndef test_two() -> None:\n    raise KeyError('k')\n", encoding="utf-8"
    )
    return tmp_path


def _classify(lines: list[str]) -> dict[str, list[str]]:
    matchers = matchers_by_kind()
    out: dict[str, list[str]] = {}
    for line in lines:
        matched = [k for k, m in matchers.items() if re.search(m["pattern"]["regexp"], line)]
        assert len(matched) <= 1, (line, matched)
        if matched:
            out.setdefault(matched[0], []).append(line)
    return out


def test_real_ruff_concise_via_env(scratch: Path) -> None:
    _needs("ruff")
    argv = [sys.executable, "-m", "ruff", "check", "--isolated", "--no-cache", "--select", "F401,F821", "src"]
    found = _classify(_run(argv, scratch, RUFF_OUTPUT_FORMAT="concise"))
    assert len(found.get("ruff", [])) == 3, found  # F401 os, F821 reveal_type, F821 undefined_name
    assert _classify(_run(argv, scratch)).get("ruff") is None  # the default (full) format is multi-line


def test_real_mypy(scratch: Path) -> None:
    _needs("mypy")
    base = [sys.executable, "-m", "mypy", "--no-incremental", "--cache-dir", os.devnull, "--strict", "src"]
    for argv in (base, [*base, "--show-column-numbers"]):
        found = _classify(_run(argv, scratch))
        assert len(found.get("mypy", [])) >= 2 and found.get("mypy-note"), found
        assert set(found) <= {"mypy", "mypy-note"}, found


def test_real_pytest(scratch: Path) -> None:
    argv = [sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", "tests"]
    found = _classify(_run(argv, scratch))
    assert found.get("pytest") and len(found["pytest"]) == 2, found
    assert found["pytest"][0].endswith(": AssertionError") and found["pytest"][1].endswith(": KeyError"), found
