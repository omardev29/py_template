def _merge(base: dict[str, Any], extra: dict[str, Any]) -> dict[str, Any]:
    out = copy.deepcopy(base)
    for key, value in extra.items():
        if isinstance(value, dict) and isinstance(out.get(key), dict):
            out[key] = _merge(out[key], value)
        else:
            out[key] = value
    return out


def preset(name: str, extra: dict[str, Any] | None = None) -> Config:
    """Return the real pytemplate.toml of a preset (package myapp, which exists in this repo's src/)."""
    text = (PRESETS / name / "files" / "pytemplate.toml").read_text("utf-8")
    data = tomllib.loads(text.replace("{{name}}", "myapp").replace("{{pkg}}", "myapp"))
    cfg: Config = config._build(Config, _merge(data, extra or {}), "")
    config.validate(cfg, COMMANDS)
    return cfg


CONFIGS: dict[str, dict[str, Any]] = {
    "script": {},
    "mypyc-active": {"backend": {"active": "mypyc"}},
    "pypy": {"backend": {"supported": ["cpython", "pypy", "mypyc"]}},
    "basedpyright": {"typing": {"editor": "basedpyright", "relaxed": "warn"}},
    "strict": {"typing": {"relaxed": "strict"}},
    "cpython-only": {"backend": {"supported": ["cpython"]}},
    "extra-buttons": {"vscode": {"buttons": ["build --method pyz", "lint", "report", "ci", "run  mypyc"]}},
}
PRESET_OF = {"raylib": "raylib", "flet": "flet"}
NAMES = [*CONFIGS, *PRESET_OF]


def make(name: str) -> Config:
    if name in PRESET_OF:
        return preset(PRESET_OF[name])
    return preset("script", CONFIGS[name])


def jsonc(text: str) -> Any:
    header, _, body = text.partition("\n")
    assert header.startswith("// GENERATED by ./deploy"), header
    return json.loads(body)


def generated(cfg: Config) -> dict[str, Any]:
    return {path: jsonc(text) for path, text in vscode.outputs(cfg, cfg.profile_for()).items()}


def task_list(cfg: Config) -> list[dict[str, Any]]:
    tasks: list[dict[str, Any]] = vscode.tasks(cfg)["tasks"]
    return tasks


def by_label(cfg: Config) -> dict[str, dict[str, Any]]:
    return {t["label"]: t for t in task_list(cfg)}


def owners(task: dict[str, Any]) -> list[str]:
    return [m["owner"].removeprefix("pytemplate-") for m in task["problemMatcher"]]


